import hashlib
import io
import logging
import shutil
import warnings
from pathlib import Path

from django.conf import settings
from django.core.files.base import ContentFile
from django.db import transaction
from PIL import Image, ImageOps, UnidentifiedImageError
from rest_framework import serializers
from rest_framework.exceptions import APIException

from .models import MediaAsset, MediaStorageState

logger = logging.getLogger(__name__)


class MediaUnavailable(APIException):
    status_code = 503
    default_detail = "Media storage is unavailable or full. Please contact the owner."


def storage_health():
    try:
        roots = [Path(settings.MEDIA_ROOT), Path(settings.PRIVATE_MEDIA_ROOT)]
        for index, root in enumerate(roots):
            root.mkdir(parents=True, exist_ok=True, mode=0o755 if index == 0 else 0o700)
        free = min(shutil.disk_usage(root).free for root in roots)
    except OSError:
        raise MediaUnavailable() from None
    if free < settings.MEDIA_MIN_FREE_BYTES:
        raise MediaUnavailable()
    if free < settings.MEDIA_WARN_FREE_BYTES:
        logger.warning("Media disk free space is below configured warning threshold")
    return free


def create_image_asset(uploaded, kind, user):
    if kind not in MediaAsset.Kind.values:
        raise serializers.ValidationError({"kind": "Choose a supported media category."})
    if uploaded.size > settings.MEDIA_UPLOAD_MAX_BYTES:
        raise serializers.ValidationError(
            {"file": "Image exceeds the configured upload size limit."}
        )
    filename = uploaded.name.replace("\\", "/").rsplit("/", 1)[-1]
    extension = Path(filename).suffix.lower()
    formats = {".png": "PNG", ".jpg": "JPEG", ".jpeg": "JPEG", ".webp": "WEBP"}
    if extension not in formats:
        raise serializers.ValidationError({"file": "Use PNG, JPEG or WebP."})
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(uploaded) as source:
                if (
                    source.format != formats[extension]
                    or source.width * source.height > settings.MEDIA_MAX_PIXELS
                ):
                    raise ValueError("Invalid image format or dimensions")
                source.verify()
            uploaded.seek(0)
            with Image.open(uploaded) as source:
                image = ImageOps.exif_transpose(source).convert("RGBA")
                image.thumbnail((1600, 1600))
    except (
        UnidentifiedImageError,
        OSError,
        ValueError,
        Image.DecompressionBombError,
        Image.DecompressionBombWarning,
    ):
        raise serializers.ValidationError(
            {"file": "Invalid, corrupt or oversized image."}
        ) from None
    optimized = io.BytesIO()
    image.save(optimized, "WEBP", quality=90)
    width, height = image.size
    image.thumbnail((320, 320))
    thumbnail = io.BytesIO()
    image.save(thumbnail, "WEBP", quality=85)
    uploaded.seek(0)
    original = uploaded.read()
    total = len(original) + optimized.tell() + thumbnail.tell()
    storage_health()
    # Seeded by migration; get_or_create also supports a freshly flushed test DB.
    MediaStorageState.objects.get_or_create(pk=1)
    failed = False
    with transaction.atomic():
        state = MediaStorageState.objects.select_for_update().get(pk=1)
        if (
            state.used_bytes + total > settings.MEDIA_MAX_STORAGE_BYTES
            or MediaAsset.objects.count() >= settings.MEDIA_MAX_ASSETS
        ):
            raise MediaUnavailable()
        asset = MediaAsset.objects.create(
            kind=kind,
            original_name=filename[:255],
            sha256=hashlib.sha256(original).hexdigest(),
            width=width,
            height=height,
            original_bytes=len(original),
            created_by=user,
        )
        saved_public = []
        try:
            asset.original.save(
                f"{kind}/originals/{asset.id.hex}{extension}", ContentFile(original), save=False
            )
            asset.file.save(
                f"{kind}/optimized/{asset.id.hex}.webp",
                ContentFile(optimized.getvalue()),
                save=False,
            )
            saved_public.append(asset.file.name)
            asset.thumbnail.save(
                f"{kind}/thumbnails/{asset.id.hex}.webp",
                ContentFile(thumbnail.getvalue()),
                save=False,
            )
            saved_public.append(asset.thumbnail.name)
            asset.total_bytes = total
            asset.status = "ready"
        except OSError:
            # Only remove variants generated by this request. Keep a valid original for recovery.
            for name in saved_public:
                try:
                    asset.file.storage.delete(name)
                except OSError:
                    logger.exception("Failed to clean incomplete media variant")
            asset.file = ""
            asset.thumbnail = ""
            asset.total_bytes = len(original) if asset.original.name else 0
            asset.status = "failed"
            asset.error_code = "storage_write_failed"
            failed = True
            logger.exception("Media write failed; no host paths returned to client")
        asset.save()
        state.used_bytes += asset.total_bytes
        state.save(update_fields=["used_bytes"])
    if failed:
        raise MediaUnavailable()
    return asset
